'use strict';
const assert=require('node:assert/strict');
const {Tracker,distance}=require('../web/motion.js');
const base=1700000000000;
const first={lat:48.45,lon:-123.5,bearing:90,speed_mps:8,timestamp:base/1000-2};
const tracker=new Tracker('victoria');
assert.equal(tracker.ingest(first,base),true);
assert.equal(tracker.sample(base).estimated,false);
const move=tracker.sample(base+1000);
assert.equal(move.estimated,true);
assert.ok(distance([first.lat,first.lon],move.point)<10);
const end=tracker.sample(base+16000);
assert.ok(distance([first.lat,first.lon],end.point)<=30.05,'prediction must be bounded');
const fresh={...first,lat:48.45005,lon:-123.4998,timestamp:first.timestamp+16};
assert.equal(tracker.ingest(fresh,base+16000),true);
const atStart=tracker.sample(base+16000);
assert.ok(distance(end.point,atStart.point)<0.03,'new fix must not snap selected marker');
const atLater=tracker.sample(base+17000);
assert.ok(distance(atStart.point,atLater.point)<25,'correction should be gradual');
assert.equal(tracker.ingest({...first,lon:-123.55,timestamp:first.timestamp+7},base+17200),false,'ignore late old GPS');
assert.equal(tracker.sample(base+17200).sourceTimestamp,fresh.timestamp);
const normal=tracker.sample(base+17000,false);
assert.deepEqual(normal.point,[fresh.lat,fresh.lon],'motion off is raw GPS');
const switchSystem=new Tracker('kelowna');
assert.equal(switchSystem.ingest(first,base,'victoria'),true);
assert.equal(switchSystem.system,'victoria');
const discontinuity=new Tracker('victoria');
discontinuity.ingest(first,base);
discontinuity.ingest({...first,lon:-123.4,timestamp:first.timestamp+30},base+30000);
assert.equal(discontinuity.sample(base+30000).reconciling,false,'large GPS jump is not falsely interpolated along a road');
console.log('V3.4 motion tests passed');
